# frozen_string_literal: true

module SilkenNet
  class Attractor
    # Класичні константи Лоренца
    BASE_SIGMA = 10.0
    BASE_RHO   = 28.0
    BASE_BETA  = 2.666 # 8.0 / 3.0
    
    # Крок інтегрування (Дельта часу для математики, не плутати з часом заряду)
    DT = 0.01

    # Цей метод викликається прямо з C-коду.
    # C-ядро передає сюди:
    # 1. seed - квантовий шум (з TRNG)
    # 2. temp - температура (°C)
    # 3. acoustic - кількість мікророзривів (кавітацій)
    def self.calculate_state(seed, temp, acoustic)
      
      # 1. Ініціалізація точки в просторі хаосу (використовуємо квантовий шум)
      # Беремо 32-бітний seed і розбиваємо його на координати від -1.0 до 1.0
      x = ((seed % 1000) / 500.0) - 1.0
      y = (((seed >> 4) % 1000) / 500.0) - 1.0
      z = (((seed >> 8) % 1000) / 500.0) - 1.0

      # 2. Пертурбація системи (Вплив фізичного світу на математику)
      # Акустичний стрес (посуха/хрускіт) збільшує швидкість зміни станів (Sigma)
      local_sigma = BASE_SIGMA + (acoustic * 0.1)
      
      # Температура впливає на "висоту конвекції" (Rho)
      local_rho = BASE_RHO + (temp * 0.2)

      # 3. Інтегрування (Прокручуємо 10 тактів Всесвіту)
      # Ми не рахуємо тисячі ітерацій, щоб берегти батарею. 
      # 10 кроків достатньо, щоб система змістилася вздовж траєкторії атрактора.
      10.times do
        dx = local_sigma * (y - x)
        dy = x * (local_rho - z) - y
        dz = (x * y) - (BASE_BETA * z)

        x += dx * DT
        y += dy * DT
        z += dz * DT
      end

      # 4. Стиснення вимірів (Колапс хвильової функції)
      # Оскільки LoRa-пейлоад обмежений, ми не можемо відправити всі три осі (x, y, z).
      # Вісь Z в Атракторі Лоренца відповідає за градієнт температур/рух маси.
      # У нашому випадку - це інтенсивність потоку соку.
      # Конвертуємо float у 8-бітне ціле число (0-255) для відправки в ефір.
      
      chaos_index = (z * 10).to_i
      
      # Захист від переповнення байта
      chaos_index = 255 if chaos_index > 255
      chaos_index = 0   if chaos_index < 0

      # Повертаємо це число назад у C-код
      return chaos_index
    end
  end
end
